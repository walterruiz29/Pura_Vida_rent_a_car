    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // 1. Validar campos vacíos
        if (txtIdPago.getText().trim().isEmpty() ||
            txtIdContrato.getText().trim().isEmpty() ||
            txtIdCliente.getText().trim().isEmpty() ||
            txtFechaPago.getText().trim().isEmpty() ||
            txtMonto.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                "Por favor complete todos los campos.",
                "Campo vacío",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 2. Obtener los valores
            int idPago = Integer.parseInt(txtIdPago.getText().trim());
            int idContrato = Integer.parseInt(txtIdContrato.getText().trim());
            int idCliente = Integer.parseInt(txtIdCliente.getText().trim());
            String fecha = txtFechaPago.getText().trim();
            double monto = Double.parseDouble(txtMonto.getText().trim());
            String metodo = (String) cmbMetodoPago.getSelectedItem();
            String estado = (String) cmbEstado.getSelectedItem();

            // 3. Validar monto
            if (monto <= 0) {
                JOptionPane.showMessageDialog(this,
                    "El monto debe ser mayor a cero.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. ¡AQUÍ ESTÁ EL CAMBIO! Guardar en el archivo
            guardarEnArchivo(idPago, idContrato, idCliente, fecha, monto, metodo, estado);

            // 5. Mensaje de éxito
            JOptionPane.showMessageDialog(this,
                "Pago registrado y guardado exitosamente!\n\n" +
                "Id Pago: " + idPago + "\n" +
                "Contrato: " + idContrato + "\n" +
                "Cliente: " + idCliente + "\n" +
                "Fecha: " + fecha + "\n" +
                "Monto: " + monto + "\n" +
                "Metodo: " + metodo + "\n" +
                "Estado: " + estado,
                "Éxito",
                JOptionPane.INFORMATION_MESSAGE);

            // 6. Limpiar campos
            txtIdPago.setText("");
            txtIdContrato.setText("");
            txtIdCliente.setText("");
            txtFechaPago.setText("");
            txtMonto.setText("");
            cmbMetodoPago.setSelectedIndex(0);
            cmbEstado.setSelectedIndex(0);
            txtIdPago.requestFocus();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                "Error: Id y Monto deben ser números válidos.",
                "Error de formato",
                JOptionPane.ERROR_MESSAGE);
        } catch (IOException ex) { // Este catch es nuevo para manejar errores de archivo
            JOptionPane.showMessageDialog(this,
                "Error al guardar el archivo: " + ex.getMessage(),
                "Error de sistema",
                JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnGuardarActionPerformed

        private void guardarEnArchivo(int idPago, int idContrato, int idCliente, 
                                  String fecha, double monto, String metodo, String estado) throws IOException {
        
        String nombreArchivo = "pagos.txt";
        
        // "true" significa que agrega al final sin borrar lo anterior
        FileWriter fw = new FileWriter(nombreArchivo, true);
        BufferedWriter bw = new BufferedWriter(fw);
        
        // Creamos una línea con los datos separados por comas
        String linea = idPago + "," + idContrato + "," + idCliente + "," + 
                       fecha + "," + monto + "," + metodo.trim() + "," + estado.trim();
        
        bw.write(linea);
        bw.newLine(); // Salto de línea para el siguiente registro
        
        bw.close();
        fw.close();
    }
        
    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
    int respuesta = JOptionPane.showConfirmDialog(
        this,
        "Esta seguro de cancelar?",
        "Confirmar",
        JOptionPane.YES_NO_OPTION
    );
    if (respuesta == JOptionPane.YES_OPTION) {
        txtIdPago.setText("");
        txtIdContrato.setText("");
        txtIdCliente.setText("");
        txtFechaPago.setText("");
        txtMonto.setText("");
        cmbMetodoPago.setSelectedIndex(0);
        cmbEstado.setSelectedIndex(0);
        dispose();
    }
    }//GEN-LAST:event_btnCancelarActionPerformed

